#!/usr/bin/env python3
"""Counts the words/JSON files of the data behind ISNAD and writes site/stats.json (run from the repo root)."""
import json, os, re, sys, datetime
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def words(o):
    n = 0
    if isinstance(o, str): return len(re.findall(r'\S+', o))
    if isinstance(o, list): return sum(words(x) for x in o)
    if isinstance(o, dict): return sum(words(v) for v in o.values())
    return 0
def scan(rel):
    files = w = size = 0
    for dp, _, fs in os.walk(os.path.join(ROOT, rel)):
        for f in fs:
            if not f.endswith('.json'): continue
            p = os.path.join(dp, f); files += 1; size += os.path.getsize(p)
            try: w += words(json.load(open(p, encoding='utf8')))
            except Exception: pass
    return {'files': files, 'words': w, 'bytes': size}
S = {}
for k, rel in [('bukhari', 'hadith/bukhari'), ('muslim', 'hadith/muslim'), ('lulu', 'hadith/lulu'), ('abudawud', 'hadith/abudawud'), ('riyad', 'hadith/riyadussalihin'), ('shamail', 'hadith/shamail'), ('quran', 'quran'), ('articles', 'articles'), ('dua', 'dua')]:
    S[k] = scan(rel)
# Quran specifics
ay = ar = ta = 0
for f in os.listdir(os.path.join(ROOT, 'quran/surah')):
    d = json.load(open(os.path.join(ROOT, 'quran/surah', f), encoding='utf8'))
    for v in d.get('verses', []): ay += 1
S['quran']['ayahs'] = ay
hadith = sum(S[k]['files'] for k in ['bukhari', 'muslim', 'lulu', 'abudawud', 'riyad', 'shamail'])
ix = os.path.join(ROOT, 'mobile/data/hadith/index.json')   # generated by mobile/tools/pack_data.py; 'have' = hadith actually in our data
if os.path.exists(ix): hadith = sum(b['have'] for b in json.load(open(ix, encoding='utf8')))
T = {'files': sum(v['files'] for v in S.values()), 'words': sum(v['words'] for v in S.values()), 'bytes': sum(v['bytes'] for v in S.values())}
out = {'generated': datetime.date.today().isoformat(), 'total': T, 'hadithFiles': hadith, 'sources': S}
json.dump(out, open(os.path.join(ROOT, 'site/stats.json'), 'w'), ensure_ascii=False, indent=1)
print(json.dumps(out, ensure_ascii=False)[:900])
